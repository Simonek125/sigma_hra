package game;

public class NPCData {
    private String id;
    private String name;
    private String description;
    private String type;
    private String dialog;

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public String getType() {
        return type;
    }

    public String getDialog() {
        return dialog;
    }
}
